CREATE TABLE IF NOT EXISTS CUST_ACCT (
    CUST_ID       VARCHAR(20) PRIMARY KEY,
    FIRST_NM      VARCHAR(60),
    LAST_NM       VARCHAR(60),
    SSN_LAST4     VARCHAR(4),
    EMP_NM        VARCHAR(120),
    EMP_STATUS    VARCHAR(20),
    ANNUAL_INCOME DECIMAL(14,2),
    MONTHLY_DEBT  DECIMAL(14,2),
    EMAIL_ADDR    VARCHAR(120),
    PHONE_NBR     VARCHAR(20),
    CREATE_TS     TIMESTAMP
);

CREATE TABLE IF NOT EXISTS LN_APPL (
    APPL_ID       VARCHAR(30) PRIMARY KEY,
    CUST_ID       VARCHAR(20),
    PROD_CD       VARCHAR(20),
    REQ_AMT       DECIMAL(14,2),
    TERM_MOS      INT,
    PURPOSE_CD    VARCHAR(40),
    COLLAT_VAL    DECIMAL(14,2),
    COLLAT_TYPE   VARCHAR(40),
    FICO_SCR      INT,
    LTV_PCT       DECIMAL(8,4),
    DTI_PCT       DECIMAL(8,4),
    BASE_RATE     DECIMAL(8,4),
    FINAL_RATE    DECIMAL(8,4),
    ELIG_CD       VARCHAR(10),
    DECISION_CD   VARCHAR(10),
    STATUS_CD     VARCHAR(20),
    CREATE_TS     TIMESTAMP,
    UPDATE_TS     TIMESTAMP
);

CREATE TABLE IF NOT EXISTS AUDIT_EVT (
    EVT_ID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPL_ID       VARCHAR(30),
    EVT_TYPE      VARCHAR(40),
    EVT_MSG       VARCHAR(500),
    EVT_TS        TIMESTAMP
);

CREATE TABLE IF NOT EXISTS DOC_CHKLIST (
    DOC_ID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPL_ID       VARCHAR(30),
    DOC_TYPE      VARCHAR(40),
    REQ_FLG       CHAR(1),
    RCVD_FLG      CHAR(1)
);

CREATE TABLE IF NOT EXISTS RATE_TBL (
    PROD_CD       VARCHAR(20) PRIMARY KEY,
    BASE_RATE     DECIMAL(8,4),
    MIN_FICO      INT,
    MAX_LTV       DECIMAL(8,4)
);
