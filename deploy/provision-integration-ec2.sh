#!/usr/bin/env bash
# One-time bootstrap: create the integration EC2 that Ansible will configure.
# Legacy model: provisioning is separate from (and prior to) configuration management.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SECRETS_DIR="${ROOT_DIR}/deploy/secrets"
KEY_NAME="${KEY_NAME:-loan-svc-integration}"
KEY_FILE="${SECRETS_DIR}/${KEY_NAME}.pem"
SG_NAME="${SG_NAME:-loan-svc-integration-sg}"
INSTANCE_NAME="${INSTANCE_NAME:-loan-svc-integration}"
INSTANCE_TYPE="${INSTANCE_TYPE:-t3.small}"
INVENTORY_FILE="${ROOT_DIR}/ansible/inventories/integration/hosts.yml"

mkdir -p "${SECRETS_DIR}"
chmod 700 "${SECRETS_DIR}"

REGION="$(aws configure get region || true)"
if [[ -z "${REGION}" ]]; then
  REGION="$(aws ec2 describe-availability-zones --query 'AvailabilityZones[0].RegionName' --output text)"
fi
export AWS_DEFAULT_REGION="${REGION}"
echo "==> Region: ${REGION}"

ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text)"
echo "==> Account: ${ACCOUNT_ID}"

if [[ ! -f "${KEY_FILE}" ]]; then
  echo "==> Creating key pair ${KEY_NAME}"
  # Delete stale AWS key with same name if local PEM is missing
  if aws ec2 describe-key-pairs --key-names "${KEY_NAME}" >/dev/null 2>&1; then
    aws ec2 delete-key-pair --key-name "${KEY_NAME}" >/dev/null
  fi
  aws ec2 create-key-pair \
    --key-name "${KEY_NAME}" \
    --query 'KeyMaterial' \
    --output text > "${KEY_FILE}"
  chmod 600 "${KEY_FILE}"
else
  echo "==> Reusing local key ${KEY_FILE}"
  if ! aws ec2 describe-key-pairs --key-names "${KEY_NAME}" >/dev/null 2>&1; then
    echo "ERROR: local PEM exists but AWS key pair ${KEY_NAME} is missing. Remove ${KEY_FILE} and re-run."
    exit 1
  fi
fi

VPC_ID="$(aws ec2 describe-vpcs --filters Name=isDefault,Values=true --query 'Vpcs[0].VpcId' --output text)"
if [[ -z "${VPC_ID}" || "${VPC_ID}" == "None" ]]; then
  echo "ERROR: no default VPC in ${REGION}"
  exit 1
fi
echo "==> Default VPC: ${VPC_ID}"

SG_ID="$(aws ec2 describe-security-groups \
  --filters "Name=group-name,Values=${SG_NAME}" "Name=vpc-id,Values=${VPC_ID}" \
  --query 'SecurityGroups[0].GroupId' --output text 2>/dev/null || true)"
if [[ -z "${SG_ID}" || "${SG_ID}" == "None" ]]; then
  echo "==> Creating security group ${SG_NAME}"
  SG_ID="$(aws ec2 create-security-group \
    --group-name "${SG_NAME}" \
    --description "Loan service integration demo (intentionally open for interview)" \
    --vpc-id "${VPC_ID}" \
    --query GroupId --output text)"
  aws ec2 authorize-security-group-ingress --group-id "${SG_ID}" \
    --ip-permissions \
    'IpProtocol=tcp,FromPort=22,ToPort=22,IpRanges=[{CidrIp=0.0.0.0/0,Description=SSH-demo}]' \
    'IpProtocol=tcp,FromPort=8080,ToPort=8080,IpRanges=[{CidrIp=0.0.0.0/0,Description=Tomcat-demo}]' \
    >/dev/null
else
  echo "==> Reusing security group ${SG_ID}"
fi

AMI_ID="$(aws ec2 describe-images \
  --owners amazon \
  --filters \
    'Name=name,Values=al2023-ami-2023*-x86_64' \
    'Name=state,Values=available' \
    'Name=architecture,Values=x86_64' \
  --query 'sort_by(Images,&CreationDate)[-1].ImageId' \
  --output text)"
echo "==> AMI: ${AMI_ID}"

EXISTING_ID="$(aws ec2 describe-instances \
  --filters \
    "Name=tag:Name,Values=${INSTANCE_NAME}" \
    "Name=instance-state-name,Values=pending,running" \
  --query 'Reservations[0].Instances[0].InstanceId' \
  --output text 2>/dev/null || true)"

if [[ -n "${EXISTING_ID}" && "${EXISTING_ID}" != "None" ]]; then
  INSTANCE_ID="${EXISTING_ID}"
  echo "==> Reusing instance ${INSTANCE_ID}"
else
  echo "==> Launching ${INSTANCE_TYPE} ${INSTANCE_NAME}"
  INSTANCE_ID="$(aws ec2 run-instances \
    --image-id "${AMI_ID}" \
    --instance-type "${INSTANCE_TYPE}" \
    --key-name "${KEY_NAME}" \
    --security-group-ids "${SG_ID}" \
    --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=${INSTANCE_NAME}},{Key=Env,Value=integration},{Key=App,Value=j2ee-loan-service}]" \
    --query 'Instances[0].InstanceId' \
    --output text)"
fi

echo "==> Waiting for instance running..."
aws ec2 wait instance-running --instance-ids "${INSTANCE_ID}"
aws ec2 wait instance-status-ok --instance-ids "${INSTANCE_ID}" || true

PUBLIC_IP="$(aws ec2 describe-instances \
  --instance-ids "${INSTANCE_ID}" \
  --query 'Reservations[0].Instances[0].PublicIpAddress' \
  --output text)"

if [[ -z "${PUBLIC_IP}" || "${PUBLIC_IP}" == "None" ]]; then
  echo "ERROR: instance has no public IP (check subnet/auto-assign public IP)"
  exit 1
fi

# Prefer a Linux-filesystem PEM path for OpenSSH (DrvFs /mnt/c is too open).
mkdir -p "${HOME}/.ssh"
cp "${KEY_FILE}" "${HOME}/.ssh/${KEY_NAME}.pem"
chmod 600 "${HOME}/.ssh/${KEY_NAME}.pem"
KEY_FILE_ABS="${HOME}/.ssh/${KEY_NAME}.pem"

cat > "${INVENTORY_FILE}" <<EOF
---
# Generated by deploy/provision-integration-ec2.sh — do not hand-edit for demo bring-up.
all:
  children:
    loan_app_servers:
      hosts:
        loan-svc-integration:
          ansible_host: ${PUBLIC_IP}
          ansible_user: ec2-user
          ansible_ssh_private_key_file: ${KEY_FILE_ABS}
EOF

echo "==> Instance ${INSTANCE_ID} @ ${PUBLIC_IP}"
echo "==> Inventory written to ${INVENTORY_FILE}"
echo "==> Next (WSL): bash deploy/run-ansible-site.sh"
echo "    App URL: http://${PUBLIC_IP}:8080/loan-service/"
